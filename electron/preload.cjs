const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('dcaApi', {
  listPortfolio: () => ipcRenderer.invoke('portfolio:list'),
  saveHolding: (holding) => ipcRenderer.invoke('portfolio:save', holding),
  deleteHolding: (id) => ipcRenderer.invoke('portfolio:delete', id),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (settings) => ipcRenderer.invoke('settings:save', settings),
  getCashSummary: () => ipcRenderer.invoke('cash:getSummary'),
  saveCashTransaction: (transaction) => ipcRenderer.invoke('cash:saveTransaction', transaction),
  deleteCashTransaction: (id) => ipcRenderer.invoke('cash:deleteTransaction', id),
  getIbkrActivityStatus: () => ipcRenderer.invoke('ibkrActivity:status'),
  chooseIbkrActivityStatement: (mode) => ipcRenderer.invoke('ibkrActivity:choosePreview', mode),
  applyIbkrActivityStatement: (token) => ipcRenderer.invoke('ibkrActivity:apply', token),
  dismissIbkrActivityReminder: (month) => ipcRenderer.invoke('ibkrActivity:dismissReminder', month),
  refreshPrices: (options) => ipcRenderer.invoke('prices:refresh', options),
  lookupSymbol: (symbol) => ipcRenderer.invoke('prices:lookupSymbol', symbol),
  searchChartSymbols: (query) => ipcRenderer.invoke('charts:searchSymbols', query),
  loadChart: (request) => ipcRenderer.invoke('charts:load', request),
  getChartQuote: (request) => ipcRenderer.invoke('charts:quote', request),
  listPrices: () => ipcRenderer.invoke('prices:list'),
  checkIbkrConnection: () => ipcRenderer.invoke('connection:checkIbkr'),
  checkYahooConnection: () => ipcRenderer.invoke('connection:checkYahoo'),
  calculatePlan: () => ipcRenderer.invoke('plan:calculate'),
  saveTodayHistory: (plan) => ipcRenderer.invoke('history:saveToday', plan),
  markBought: (payload) => ipcRenderer.invoke('history:markBought', payload),
  listBuyLog: () => ipcRenderer.invoke('buyLog:list'),
  saveBuyLog: (payload) => ipcRenderer.invoke('buyLog:save', payload),
  deleteBuyLog: (id) => ipcRenderer.invoke('buyLog:delete', id),
  listPendingOrders: () => ipcRenderer.invoke('pendingOrders:list'),
  savePendingOrder: (payload) => ipcRenderer.invoke('pendingOrders:save', payload),
  cancelPendingOrder: (id) => ipcRenderer.invoke('pendingOrders:cancel', id),
  markPendingOrderReady: (id) => ipcRenderer.invoke('pendingOrders:markReady', id),
  deletePendingOrder: (id) => ipcRenderer.invoke('pendingOrders:delete', id),
  exportBuyLogCsv: () => ipcRenderer.invoke('buyLog:exportCsv'),
  listHistory: () => ipcRenderer.invoke('history:list'),
  exportCsv: () => ipcRenderer.invoke('history:exportCsv'),
  exportReportCsv: (history) => ipcRenderer.invoke('history:exportReportCsv', history),
});
